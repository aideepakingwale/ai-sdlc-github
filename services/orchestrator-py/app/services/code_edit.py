"""Prompt-based code editing: a code assistant that works on the files a person selects.

Like the coding assistants people use in an editor, it is an agent loop and not a single prompt. It lists folders, reads files, searches,
edits with exact replacements, writes and deletes files and checks syntax, one turn after another, and then reports. Everything it does
happens on an in-memory overlay of the workspace: nothing is written to the project until a person reviews the diff and applies it, and
an applied edit can be undone.

Two workspaces: the code the implementation stage generated (artefacts of the code stage) and the codebase a person uploaded. The
instructions are the `code-editor` agent file (agents/code/code-editor.md).
"""
